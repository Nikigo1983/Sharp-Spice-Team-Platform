const MODE_INSTRUCTIONS: Record<WorkspaceResponseMode, string> = {
  brief: `Режим: КРАТКО.
Ответь максимально сжато: короткий вывод + 3–5 пунктов «что важно» + 1–2 шага «что дальше».
Не больше ~150 слов, если менеджер не просил иначе.`,

  detailed: `Режим: ПОДРОБНО.
Дай больше деталей и нюансов, но сохраняй живой разговорный тон.
Структура: вывод → что важно (списком) → что сделать дальше → при необходимости уточняющие вопросы.
Без сухих отчётов и без копирования всего контекста.`,

  "client-text": `Режим: ТЕКСТ КЛИЕНТУ.
Напиши готовое сообщение клиенту — тёплое, профессиональное, человеческое.
Можно сразу скопировать и отправить в WhatsApp или email.
Без внутренних пометок, без «для менеджера», без технического жаргона.
Если данных не хватает — напиши черновик и явно отметь, что нужно уточнить у клиента.`,

  "case-analysis": `Режим: АНАЛИЗ КЕЙСА.
Разбери ситуацию структурно, но живым языком:
1. Суть кейса (2–3 предложения)
2. Что уже есть в данных
3. Риски и пробелы
4. Рекомендуемые следующие шаги
Без канцелярита и без длинных таблиц — только смысл.`,
};

export function buildWorkspaceSystemPrompt(
  mode: WorkspaceResponseMode = "brief",
): string {
  return `${WORKSPACE_BASE_PROMPT}\n\n${MODE_INSTRUCTIONS[mode]}`;
}
